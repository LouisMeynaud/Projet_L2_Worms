package com.lllmtb.model.entity.team;

/**
 * Enumeration representing the possible colors that a {@link Team} can have.
 * <p>Each color is used to visually distinguish teams during gameplay.</p>
 * <p>Available colors:</p>
 * <ul>
 *   <li>{@link #RED}</li>
 *   <li>{@link #BLUE}</li>
 *   <li>{@link #GREEN}</li>
 *   <li>{@link #YELLOW}</li>
 * </ul>
 */
public enum TeamColor {
    RED,
    BLUE,
    GREEN,
    YELLOW,
}
